export const HORIZON_ROUTES = REGIONS.filter((r) => r.generated).flatMap((r) => r.trails);

export const REGION_BY_ID = Object.fromEntries(REGIONS.map((r) => [r.id, r]));

export function getRegion(id) {
  return REGION_BY_ID[id] || REGIONS[0];
}

const TRAIL_REGION = {};
REGIONS.forEach((region) => {
  const ids = region.generated
    ? region.trails.map((t) => t.id)
    : region.trailIds;
  ids.forEach((tid) => { TRAIL_REGION[tid] = region.id; });
});

export function regionIdForTrail(trailId) {
  return TRAIL_REGION[trailId] || null;
}

export function regionBadgeEarned(trails, regionId) {
  const region = getRegion(regionId);
  if (!region || !region.badge) return false;
  const p = trails && trails.progress && trails.progress[region.badge.trail];
  return !!(p && p.pin);
}

const FAMILY_COUNT = REGIONS.reduce((n, r) => n + r.ecology.families.length, 0);
if (FAMILY_COUNT !== 58) {
  throw new Error(`regions: expected 58 families, got ${FAMILY_COUNT}`);
}
if (HORIZON_ROUTES.length !== 20) {
  throw new Error(`regions: expected 20 horizon trails, got ${HORIZON_ROUTES.length}`);
}
const horizonFaces = HORIZON_ROUTES.flatMap((r) => r.companions);
if (new Set(horizonFaces).size !== horizonFaces.length) {
  throw new Error('regions: a companion is listed on two Horizon trails');
}
if (new Set(HORIZON_ROUTES.map((r) => r.stageTone)).size !== 20) {
  throw new Error('regions: two Horizon trails share a sky tone');
}
if (new Set(HORIZON_ROUTES.map((r) => r.mapId)).size !== 20) {
  throw new Error('regions: two Horizon trails share a map id');
}

